#!/usr/bin/env node
// apps/web/scripts/build-plane-publish.mjs
//
// D#598 P1f-5b: the build step for the publish hook (`fx-plane-publish.mjs`). The worker writes the hook into a publish sandbox as one file; its
// bytes must come from the BUILT output and must not be read from a path at run time (a deployed function has no checkout). So this bundles the
// hook's entry (packages/runner/src/planePublish/main.ts) with esbuild and writes the bundle's text into a generated TS module, which the
// worker's ports import. It is the same pattern as copy-workspace.mjs (the workspace index): nothing is opened after the build.
//
// The step FAILS the build if the bundle holds the build machine's path (check-baked-paths scans the server output for the same thing; this
// catches it a stage earlier, on the bundle alone). The generated module is gitignored with the rest of app/_generated/.
import { createHash } from "node:crypto";
import { mkdirSync, realpathSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { buildSync } from "esbuild";

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const WEB_DIR = join(SCRIPT_DIR, "..");
const REPO_ROOT = join(WEB_DIR, "..", "..");
const ENTRY = join(REPO_ROOT, "packages", "runner", "src", "planePublish", "main.ts");
const GENERATED_DIR = join(WEB_DIR, "app", "_generated");
export const GENERATED_FILE = join(GENERATED_DIR, "plane-publish-hook.ts");

/** The bundled hook as text. Throws if the bundle holds the build machine's path. */
export function bundlePlanePublishHook() {
  const out = buildSync({ entryPoints: [ENTRY], bundle: true, platform: "node", format: "esm", write: false, logLevel: "silent", legalComments: "none" });
  const file = out.outputFiles?.[0];
  if (out.outputFiles?.length !== 1 || !file) throw new Error("build-plane-publish: expected exactly one bundle");
  const text = file.text;
  for (const root of new Set([REPO_ROOT, realpathSync(REPO_ROOT)])) {
    if (text.includes(root)) throw new Error("build-plane-publish: the hook bundle holds the build machine's path");
  }
  return text;
}

export function buildPlanePublish() {
  const source = bundlePlanePublishHook();
  const sha256 = createHash("sha256").update(source).digest("hex");
  mkdirSync(GENERATED_DIR, { recursive: true });
  writeFileSync(
    GENERATED_FILE,
    `// GENERATED by scripts/build-plane-publish.mjs -- do not edit. The built publish hook (fx-plane-publish.mjs) as text.\n` +
      `export const PLANE_PUBLISH_HOOK_SOURCE: string = ${JSON.stringify(source)};\n` +
      `export const PLANE_PUBLISH_HOOK_SHA256: string = ${JSON.stringify(sha256)};\n`,
  );
  return { sha256, bytes: Buffer.byteLength(source) };
}

if (process.argv[1] && join(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const r = buildPlanePublish();
  console.log(`build-plane-publish: ok (${r.bytes} bytes, sha256 ${r.sha256.slice(0, 12)})`);
}
