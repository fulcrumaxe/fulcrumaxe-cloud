#!/usr/bin/env node
// apps/web/scripts/copy-workspace.mjs
//
// D#37 WS-C2 criterion 1: "apps/web serves the built workspace: `/`
// returns the filtered `index.html`... The copy step runs before
// `next build` and fails if `dist/` fails WS-A1's checks."
//
// Runs apps/workspace's own profile-filtered build (build/build.mjs's
// `build()`), which already performs WS-A1's checks.mjs --import and
// --ship gates as part of its own pipeline (see that file) and throws
// if either fails. This script does not duplicate that check -- it
// just lets the throw propagate, which fails `next build` (and, via
// apps/web/test/globalSetup.ts, fails `vitest run` too, before any
// route.ts test could otherwise run against stale or missing output).
//
// Then copies the result into the two places apps/web actually serves
// from:
//   - every file except index.html -> apps/web/public/ (Next's own
//     static file server). apps/web/public/ is entirely generated by
//     this script and gitignored -- it is wiped and rewritten on every
//     run, never hand-edited.
//   - index.html's contents -> a generated TS module
//     (apps/web/app/_generated/workspace-index.ts) that app/route.ts
//     imports directly, so `/` needs no runtime filesystem access (and
//     the committed copy keeps `tsc`/`vitest` working before this
//     script has ever run in a given checkout -- see that file's own
//     header comment).
//
// Usage: node copy-workspace.mjs (or import { copyWorkspace } and call
// it directly -- test/globalSetup.ts and the "prebuild" package.json
// script both do this).

import { mkdirSync, rmSync, existsSync, readFileSync, writeFileSync, copyFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const WEB_DIR = join(SCRIPT_DIR, "..");
const WORKSPACE_DIR = join(WEB_DIR, "..", "workspace");
const PUBLIC_DIR = join(WEB_DIR, "public");
const GENERATED_DIR = join(WEB_DIR, "app", "_generated");
const GENERATED_FILE = join(GENERATED_DIR, "workspace-index.ts");

export async function copyWorkspace() {
  const { build, shippedPath } = await import(join(WORKSPACE_DIR, "build", "build.mjs"));
  const result = build(); // throws on any checks.mjs --import/--ship failure

  // apps/web/public/ is entirely generated output -- wipe it before
  // every copy so a file dropped from a later shell import doesn't
  // linger as a stale, unreferenced asset.
  if (existsSync(PUBLIC_DIR)) rmSync(PUBLIC_DIR, { recursive: true, force: true });
  mkdirSync(PUBLIC_DIR, { recursive: true });

  // D#37 WS-D criterion 3: every file build() shipped (everything but
  // index.html) lives under Next's public/ at the SAME content-hashed
  // s/<hash>/ prefix build() gave it, so a request for
  // /s/<hash>/core/boot.js resolves to public/s/<hash>/core/boot.js --
  // Next serves public/** at the site root with no rewrite needed. index.html
  // itself is never copied here; it goes into the generated TS module below.
  for (const relPath of result.copiedFiles) {
    const destAbs = join(PUBLIC_DIR, "s", result.hash, ...relPath.split("/"));
    mkdirSync(dirname(destAbs), { recursive: true });
    copyFileSync(shippedPath(result, relPath), destAbs);
  }

  const indexHtml = readFileSync(join(result.outDir, "index.html"), "utf8");
  mkdirSync(GENERATED_DIR, { recursive: true });
  const generated =
    "// GENERATED by apps/web/scripts/copy-workspace.mjs -- do not hand-edit.\n" +
    "// D#37 WS-C2 criterion 1: the filtered workspace index.html, served at `/`\n" +
    "// by apps/web/app/route.ts. Regenerated on every `next build` (prebuild)\n" +
    "// and before every vitest run of the \"web\" project (test/globalSetup.ts).\n" +
    `export const WORKSPACE_INDEX_HTML = ${JSON.stringify(indexHtml)};\n`;
  // Security fix round item 6 (should-fix): GENERATED_FILE is a TRACKED
  // file, deliberately committed (see the header comment above) so a
  // fresh checkout has working tsc/vitest before copyWorkspace() has
  // ever run there. It must stay tracked for that bootstrap case, but
  // test/globalSetup.ts calls this function before EVERY "web" vitest
  // run -- an unconditional writeFileSync touched the tracked file's
  // mtime (and, whenever apps/workspace's source had genuinely changed
  // since the last commit here, its content) on every single test run,
  // which is what the security review's code-review note flagged: a
  // test run silently leaving an uncommitted diff behind. Comparing
  // against what's already on disk first means a test run is a true
  // no-op -- no write at all -- whenever the committed copy already
  // matches a fresh build (the common case: whoever last touched
  // apps/workspace also regenerated and committed this file). A write
  // still happens, exactly as before, when the two genuinely differ --
  // that's this file doing its one job (never silently testing a stale
  // copy), not a regression.
  let existing = null;
  try {
    existing = readFileSync(GENERATED_FILE, "utf8");
  } catch {
    // File doesn't exist yet (first run in this checkout) -- fall through to write it.
  }
  if (existing !== generated) {
    writeFileSync(GENERATED_FILE, generated);
  }

  return { ...result, publicDir: PUBLIC_DIR, generatedFile: GENERATED_FILE };
}

function main() {
  copyWorkspace()
    .then((result) => {
      console.log(
        `copy-workspace.mjs: wrote ${result.copiedFiles.length} file(s) to ${result.publicDir}, ` +
          `index.html to ${result.generatedFile}`,
      );
    })
    .catch((err) => {
      console.error(err && err.message ? err.message : String(err));
      process.exitCode = 1;
    });
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main();
}
