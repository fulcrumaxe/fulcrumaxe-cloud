import type { PoolClient } from 'pg';
import { pairingDigest } from '@fulcrumaxe/runner-protocol/pairingDigest';

/**
 * D#598 P1f-1: the platform's record of what it pushed to a paired PUBLIC repo for a work item (migration 0831, `plane_pushes`).
 * Every function takes a `PoolClient` already inside a tenant transaction (`withTenant`), so the caller decides what commits with it.
 * Nothing here calls GitHub: `derivePlanePush` is handed a port that reads a branch head.
 *
 * The row is a STAMP of what the platform last saw, never the truth. GitHub's branch head wins on every read: `derivePlanePush`
 * returns GitHub's value and says whether the stamp is stale, and it never writes GitHub's value over the stamp. The pairing is read
 * ONCE, at build start (`stampPlanePush`): later pushes compare their own reading with the stored digest, so a pairing that moved
 * after the build began is noticed (`pairing_changed`) instead of silently followed.
 */

type Queryable = Pick<PoolClient, 'query'>;

/** The P1f states and the P1g states, together (the database enforces the same list). */
export const PLANE_PUSH_STATES = [
  'building',
  'scanning',
  'pushed',
  'pr_opened',
  'refused',
  'pushed_pr_not_opened',
  'no_public_change',
  'updating',
  'updated',
  'waiting_person_pushed',
  'managed_by_person',
  'pr_closed',
  'pr_merged',
] as const;
export type PlanePushState = (typeof PLANE_PUSH_STATES)[number];

/** A state a P1f outcome may be recorded as. */
export type PlanePushOutcomeState = 'scanning' | 'pushed' | 'pr_opened' | 'refused' | 'pushed_pr_not_opened' | 'no_public_change';

/** The states a P1f outcome never overwrites: a pull request exists, or someone has taken the branch over. */
const SETTLED: readonly PlanePushState[] = ['pr_opened', 'updating', 'updated', 'waiting_person_pushed', 'managed_by_person', 'pr_closed', 'pr_merged'];
/** The states a new build may re-stamp (a fresh attempt at the same item). */
const RESTAMPABLE: readonly PlanePushState[] = ['building', 'scanning', 'refused', 'no_public_change'];

/** A push has at most this many attempts per row (the schema checks the same number). */
export const PUBLISH_ATTEMPT_LIMIT = 3;

/** What the retry predicate needs: the push row's state, the runtime of its latest push attempt, and how many push attempts it has. */
export interface RetryFacts {
  state: PlanePushState;
  lastPushRuntime: 'runner' | 'sandbox' | 'hosted' | null;
  pushAttempts: number;
  managedByPerson: boolean;
}

/**
 * THE one predicate for "may this item try the push again now": a refused push of a sandbox build with fewer than three push attempts. The worker's
 * `retryPublish` enforces it, and the `retry_push` operator action and the item view's `actions` list themselves from it, so the page never offers a retry that
 * would be refused. (A `pushed_pr_not_opened` item is not here: that retry opens the PR with no sandbox, and its action is `open_pr`.)
 */
export function mayRetryPublish(f: RetryFacts): boolean {
  return f.state === 'refused' && f.lastPushRuntime === 'sandbox' && f.pushAttempts < PUBLISH_ATTEMPT_LIMIT && !f.managedByPerson;
}

/** Whether "Open the pull request again" applies: the branch is pushed, no pull request exists, and nobody has taken the branch over. */
export function mayOpenPublicPullRequest(f: RetryFacts): boolean {
  return f.state === 'pushed_pr_not_opened' && !f.managedByPerson;
}

/**
 * The one address a pull request of the paired repository has: `https://github.com/<code_repo>/pull/<number>`. A recorded or reported address must be exactly this
 * (the repository's case is GitHub's and is not compared), so a link on the page can never lead to another repository or another pull request.
 */
export function publicPullRequestUrlMatches(codeRepo: string, prNumber: number, url: unknown): boolean {
  return typeof url === 'string' && Number.isSafeInteger(prNumber) && prNumber > 0 && url.toLowerCase() === `https://github.com/${codeRepo}/pull/${prNumber}`.toLowerCase();
}

export interface PlanePushRow {
  id: string;
  accountId: string;
  workItemId: string;
  repoId: string;
  codeRepo: string;
  pairingDigest: string;
  /** `fx/p-<id>`, generated by the database from the row's own id. */
  branch: string;
  headSha: string | null;
  tipSha: string | null;
  prNumber: number | null;
  prUrl: string | null;
  state: PlanePushState;
  code: string | null;
  refusals: PlaneRefusalEntry[];
  managedByPersonAt: Date | null;
  createdAt: Date;
  updatedAt: Date;
}

/** What a refusal may say: which kind, where, and which rule. Never the matched value, a file's content or a token. */
export interface PlaneRefusalEntry {
  kind: string;
  place: string;
  rule_key: string;
}

export const MAX_REFUSALS = 100;

interface Row {
  id: string;
  account_id: string;
  work_item_id: string;
  repo_id: string;
  code_repo: string;
  pairing_digest: string;
  branch: string;
  head_sha: string | null;
  tip_sha: string | null;
  pr_number: number | null;
  pr_url: string | null;
  state: PlanePushState;
  code: string | null;
  refusals: PlaneRefusalEntry[];
  managed_by_person_at: Date | null;
  created_at: Date;
  updated_at: Date;
}

const COLUMNS = `id, account_id, work_item_id, repo_id, code_repo, pairing_digest, branch, head_sha, tip_sha, pr_number, pr_url, state, code, refusals, managed_by_person_at, created_at, updated_at`;

function toRow(r: Row): PlanePushRow {
  return {
    id: r.id,
    accountId: r.account_id,
    workItemId: r.work_item_id,
    repoId: r.repo_id,
    codeRepo: r.code_repo,
    pairingDigest: r.pairing_digest,
    branch: r.branch,
    headSha: r.head_sha,
    tipSha: r.tip_sha,
    prNumber: r.pr_number,
    prUrl: r.pr_url,
    state: r.state,
    code: r.code,
    refusals: r.refusals,
    managedByPersonAt: r.managed_by_person_at,
    createdAt: r.created_at,
    updatedAt: r.updated_at,
  };
}

export class PlanePushRecordError extends Error {
  constructor(
    readonly code: 'bad_outcome',
    message: string,
  ) {
    super(message);
    this.name = 'PlanePushRecordError';
  }
}

/**
 * The pairing digest has one copy, in the runner protocol package (the pairing reply recomputes it and the runner-side code cannot import this
 * package). Re-exported so the stamp and the routes keep one import path.
 */
export { pairingDigest, type PairingForDigest } from '@fulcrumaxe/runner-protocol/pairingDigest';

export interface StampInput {
  accountId: string;
  workItemId: string;
  /** The PRIVATE repo the item is built in. */
  repoId: string;
  /**
   * A replay of a build step that already started its run: make sure the row exists, but leave an existing one exactly as it is (the run
   * may already have moved it on). A fresh build, or a Build again, leaves this off and re-stamps.
   */
  replay?: boolean;
}

/**
 * Called at build start. If the repo has a pairing row, writes (or re-stamps) the item's `plane_pushes` row with the repo's full name,
 * the pairing digest and the branch the database generated; returns it. If the repo has NO pairing row it writes nothing and returns
 * null: no row means the single-repo path, exactly as today.
 *
 * A second build of the same item (Build again) re-stamps the digest and sets the state back to `building` only while the row is in a
 * state a new attempt may replace (`building`, `scanning`, `refused`, `no_public_change`). A row that has pushed, or has a pull request,
 * keeps its record: the branch exists and nothing here may pretend otherwise. The row is returned either way.
 */
export async function stampPlanePush(client: Queryable, input: StampInput): Promise<PlanePushRow | null> {
  const { rows: pairs } = await client.query<{ code_repo: string; overlay_globs: string[]; identifier_rules_path: string | null; plan_data_rules_path: string | null }>(
    'SELECT code_repo, overlay_globs, identifier_rules_path, plan_data_rules_path FROM repo_pairing WHERE repo_id = $1 AND account_id = $2',
    [input.repoId, input.accountId],
  );
  const pair = pairs[0];
  if (!pair) return null;
  const digest = pairingDigest({ codeRepo: pair.code_repo, overlayGlobs: pair.overlay_globs, identifierRulesPath: pair.identifier_rules_path, planDataRulesPath: pair.plan_data_rules_path });
  const onConflict =
    input.replay === true
      ? 'ON CONFLICT (account_id, work_item_id, lower(code_repo)) DO NOTHING'
      : `ON CONFLICT (account_id, work_item_id, lower(code_repo)) DO UPDATE
        SET pairing_digest = EXCLUDED.pairing_digest, state = 'building', code = NULL, refusals = '[]'::jsonb
      WHERE plane_pushes.state = ANY ($6::text[])`;
  await client.query(
    `INSERT INTO plane_pushes (account_id, work_item_id, repo_id, code_repo, pairing_digest)
     VALUES ($1, $2, $3, $4, $5)
     ${onConflict}`,
    input.replay === true ? [input.accountId, input.workItemId, input.repoId, pair.code_repo, digest] : [input.accountId, input.workItemId, input.repoId, pair.code_repo, digest, RESTAMPABLE],
  );
  const { rows } = await client.query<Row>(`SELECT ${COLUMNS} FROM plane_pushes WHERE account_id = $1 AND work_item_id = $2 AND lower(code_repo) = lower($3)`, [
    input.accountId,
    input.workItemId,
    pair.code_repo,
  ]);
  return rows[0] ? toRow(rows[0]) : null;
}

/** The item's record for one paired repo, or null when it has none (an unpaired item). */
export async function readPlanePush(client: Queryable, accountId: string, workItemId: string): Promise<PlanePushRow | null> {
  const { rows } = await client.query<Row>(`SELECT ${COLUMNS} FROM plane_pushes WHERE account_id = $1 AND work_item_id = $2 ORDER BY created_at DESC, id LIMIT 1`, [accountId, workItemId]);
  return rows[0] ? toRow(rows[0]) : null;
}

export interface VerifiedOutcome {
  state: PlanePushOutcomeState;
  /** For `refused`: one of the push route's fixed refusal codes. */
  code?: string;
  refusals?: readonly PlaneRefusalEntry[];
  headSha?: string;
  tipSha?: string;
  prNumber?: number;
  prUrl?: string;
}

const SHA = /^([0-9a-f]{40}|[0-9a-f]{64})$/;
const CODE = /^[a-z][a-z0-9_]{0,63}$/;
const KIND = /^[a-z][a-z0-9_]{0,63}$/;
// eslint-disable-next-line no-control-regex
const CONTROL = /[\u0000-\u001f\u007f-\u009f\u2028\u2029]/g;

/** Fixed-shape text only: control characters removed, length capped. A value that would not fit is cut, never rewritten. */
function clean(text: unknown, max: number): string {
  return typeof text === 'string' ? text.replace(CONTROL, ' ').slice(0, max) : '';
}

/** At most 100 entries, each `{kind, place, rule_key}` and nothing else: any other field a caller supplies is dropped here. */
export function cleanRefusals(list: readonly PlaneRefusalEntry[] | undefined): PlaneRefusalEntry[] {
  return (list ?? []).slice(0, MAX_REFUSALS).map((r) => ({
    kind: KIND.test(String(r?.kind)) ? String(r.kind) : 'unknown',
    place: clean(r?.place, 300),
    rule_key: clean(r?.rule_key, 200),
  }));
}

/**
 * Records an outcome the caller has ALREADY verified against GitHub (a runner's report is a hint; the hosted side reads the branch and
 * the PR first). The record is a stamp: this does not read GitHub. Returns the row, or null when nothing was recorded because the row is
 * settled (its state says a pull request exists or a person has the branch, or `managed_by_person_at` is set): a late report from a retried attempt cannot move it back.
 */
export async function recordVerifiedOutcome(client: Queryable, input: { accountId: string; id: string; outcome: VerifiedOutcome }): Promise<PlanePushRow | null> {
  const o = input.outcome;
  const bad = (why: string): never => {
    throw new PlanePushRecordError('bad_outcome', `plane push outcome ${o.state}: ${why}`);
  };
  const needSha = o.state === 'pushed' || o.state === 'pr_opened' || o.state === 'pushed_pr_not_opened';
  if (needSha && (!o.headSha || !SHA.test(o.headSha) || !o.tipSha || !SHA.test(o.tipSha))) bad('needs the pushed head and the tip it was built on');
  if (o.headSha !== undefined && !SHA.test(o.headSha)) bad('head is not a full sha');
  if (o.tipSha !== undefined && !SHA.test(o.tipSha)) bad('tip is not a full sha');
  if (o.state === 'pr_opened' && (!Number.isSafeInteger(o.prNumber) || o.prNumber! <= 0 || typeof o.prUrl !== 'string')) bad('needs the pull request number and url');
  if (o.state === 'refused' && (o.code === undefined || !CODE.test(o.code))) bad('needs a refusal code');
  if (o.state !== 'refused' && o.code !== undefined) bad('only a refusal carries a code');
  if (o.state !== 'pr_opened' && (o.prNumber !== undefined || o.prUrl !== undefined)) bad('only an opened pull request carries a number and url');

  if (o.state === 'pr_opened') {
    const { rows: repo } = await client.query<{ code_repo: string }>('SELECT code_repo FROM plane_pushes WHERE id = $1 AND account_id = $2', [input.id, input.accountId]);
    if (!repo[0]) return null;
    if (!publicPullRequestUrlMatches(repo[0].code_repo, o.prNumber!, o.prUrl)) bad('the pull request url is not this pull request in the paired repository');
  }

  const { rows } = await client.query<Row>(
    `UPDATE plane_pushes
        SET state = $3,
            code = $4,
            refusals = $5::jsonb,
            head_sha = COALESCE($6, head_sha),
            tip_sha = COALESCE($7, tip_sha),
            pr_number = COALESCE($8, pr_number),
            pr_url = COALESCE($9, pr_url)
      WHERE id = $1 AND account_id = $2 AND managed_by_person_at IS NULL AND NOT (state = ANY ($10::text[]))
      RETURNING ${COLUMNS}`,
    [
      input.id,
      input.accountId,
      o.state,
      o.state === 'refused' ? o.code! : null,
      JSON.stringify(o.state === 'refused' ? cleanRefusals(o.refusals) : []),
      o.headSha ?? null,
      o.tipSha ?? null,
      o.prNumber ?? null,
      o.prUrl ?? null,
      SETTLED,
    ],
  );
  return rows[0] ? toRow(rows[0]) : null;
}

/** Reads a branch's head on the public repo: the 40-hex sha, or null when the branch does not exist. The caller supplies the adapter: `createPlanePushApi().branchHead` takes a token, so P1f-2 wraps it in one that mints a fresh token and revokes it around the read. */
export interface BranchHeadPort {
  branchHead(input: { codeRepo: string; branch: string }): Promise<string | null>;
}

export interface DerivedPlanePush {
  row: PlanePushRow;
  /** GitHub's value (null: no such branch). This is the one to act on. */
  headSha: string | null;
  /** True when the stamp's `head_sha` is not what GitHub says. The stamp is NOT changed. */
  stale: boolean;
}

/**
 * The truth for a read: asks GitHub for the branch head and returns it next to the stamp. When they differ the result says `stale`
 * and carries GitHub's value; nothing is written. A caller that acts on a mismatch (a fix round, a state shown to a person) uses
 * `headSha`, and `recordVerifiedOutcome` is the only way the stamp moves. A port failure is the caller's to handle: this does not
 * fall back to the stamp, because a stamp presented as GitHub's answer is exactly the mistake this exists to prevent.
 */
export async function derivePlanePush(client: Queryable, input: { accountId: string; id: string }, port: BranchHeadPort): Promise<DerivedPlanePush | null> {
  const { rows } = await client.query<Row>(`SELECT ${COLUMNS} FROM plane_pushes WHERE id = $1 AND account_id = $2`, [input.id, input.accountId]);
  if (!rows[0]) return null;
  const row = toRow(rows[0]);
  const headSha = await port.branchHead({ codeRepo: row.codeRepo, branch: row.branch });
  return { row, headSha, stale: headSha !== row.headSha };
}

/**
 * The facts the two retry predicates need for an item's latest push row (the row `readPublicChange` shows). An item refused before any sandbox was started
 * has no attempt yet; its executor ran in the sandbox, so the retry is a sandbox retry (the worker's reader makes the same reading). Null for an item with no row.
 */
export async function readRetryFacts(client: Queryable, workItemId: string): Promise<RetryFacts | null> {
  const { rows } = await client.query<{ state: PlanePushState; managed: boolean; n: number; last: RetryFacts['lastPushRuntime']; sandbox_side: boolean | null }>(
    `SELECT p.state, p.managed_by_person_at IS NOT NULL AS managed,
            (SELECT count(*)::int FROM plane_push_attempts a WHERE a.account_id = p.account_id AND a.plane_push_id = p.id AND a.kind = 'push') AS n,
            (SELECT (array_agg(a.runtime ORDER BY a.attempt_no DESC))[1] FROM plane_push_attempts a WHERE a.account_id = p.account_id AND a.plane_push_id = p.id AND a.kind = 'push') AS last,
            (SELECT r.job_signed IS NULL AND r.runtime = 'production' FROM agent_runs r WHERE r.account_id = p.account_id AND r.work_item_id = p.work_item_id AND r.role = 'executor'
              ORDER BY r.created_at DESC, r.id LIMIT 1) AS sandbox_side
       FROM plane_pushes p WHERE p.work_item_id = $1 ORDER BY p.created_at DESC, p.id LIMIT 1`,
    [workItemId],
  );
  const r = rows[0];
  if (!r) return null;
  return { state: r.state, managedByPerson: r.managed === true, pushAttempts: r.n, lastPushRuntime: r.last ?? (r.sandbox_side === true ? 'sandbox' : null) };
}
