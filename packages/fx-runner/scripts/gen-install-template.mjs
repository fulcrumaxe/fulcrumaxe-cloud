#!/usr/bin/env node
// Writes scripts/install-template.generated.mjs: the text of install.sh as a string, so the cloud's install route (which has no
// file next to it once built) renders the very same template the release copy is made from. Run it after every edit of install.sh;
// test/update/installVerify.test.ts fails when the two differ. Same pattern as src/update/trustedRoot.ts.
//
//   node scripts/gen-install-template.mjs
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const text = readFileSync(path.join(here, "..", "install.sh"), "utf8");
const body = [
  "/**",
  " * GENERATED by scripts/gen-install-template.mjs from install.sh. Do not edit: change install.sh and run the script again.",
  " * A test compares this text with the file byte for byte.",
  " */",
  `export const INSTALL_TEMPLATE_TEXT = ${JSON.stringify(text)};`,
  "",
].join("\n");
writeFileSync(path.join(here, "..", "scripts", "install-template.generated.mjs"), body);
