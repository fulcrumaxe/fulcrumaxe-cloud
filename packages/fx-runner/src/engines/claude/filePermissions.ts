import path from "node:path";
import type { ProtectedPaths } from "../../sandbox/sandboxSettings.js";
import { SANDBOX_PROTECTED_FILES } from "../../daemon/sandboxStubs.js";
import { EngineRefusal } from "./refusal.js";

/**
 * Permission rules for the agent's own file tools, in the syntax the CLI documents (checked against the Claude Code
 * permissions page, 2026-10-08): path rules are consulted for `Read(...)` and `Edit(...)` only. A `Read` rule also covers
 * Glob, Grep and LS; an `Edit` rule covers Write, MultiEdit and NotebookEdit. A path rule written for any of those
 * tools by name is accepted and never consulted. `//abs/path` is an absolute path, gitignore globs apply.
 */
const READ_TOOLS: ReadonlySet<string> = new Set(["Read", "Glob", "Grep", "LS"]);
const EDIT_TOOLS: ReadonlySet<string> = new Set(["Edit", "Write", "MultiEdit", "NotebookEdit"]);

/** Characters that would be a glob, a negation, an escape or a rule delimiter inside a rule. */
const RULE_META = /[*?[\]{}!\\()\n\r]/;

/** `//abs/path`: the CLI's spelling of an absolute path. A path that cannot be written literally is refused, never guessed at. */
export function anchored(abs: string): string {
  if (!path.isAbsolute(abs) || RULE_META.test(abs)) throw new EngineRefusal("bad_start_options", "path cannot be written as a permission rule");
  return `/${abs.length > 1 && abs.endsWith("/") ? abs.slice(0, -1) : abs}`;
}

/**
 * Turns each bare file tool of a role entry into a rule confined to `workspace`. Read tools become `Read` rules, edit
 * tools `Edit` rules (the only two spellings the CLI consults); every other entry passes through. Order is kept and an
 * entry that maps to a rule already present is not repeated.
 */
export function confineFileTools(roleEntry: readonly string[], workspace: string): string[] {
  const root = anchored(workspace);
  const out: string[] = [];
  for (const tool of roleEntry) {
    const rules = READ_TOOLS.has(tool) ? [`Read(${root})`, `Read(${root}/**)`] : EDIT_TOOLS.has(tool) ? [`Edit(${root}/**)`] : [tool];
    for (const rule of rules) if (!out.includes(rule)) out.push(rule);
  }
  return out;
}

/** D#600 CX-4b: the `Read` rules (which cover Glob, Grep and LS) for one directory the agent may read and not change. A path that cannot be written literally is refused. */
export function readRulesFor(abs: string): string[] {
  return [`Read(${anchored(abs)})`, `Read(${anchored(abs)}/**)`];
}

/**
 * The deny floor, generated from the one protected list. A path may be a file or a directory, so each gets a rule for
 * itself and one for what is under it. Deny outranks allow, so this holds even if the allow entries are wrong.
 */
export function denyRules(protectedList: ProtectedPaths): string[] {
  const both = (tool: "Read" | "Edit", abs: string): string[] => [`${tool}(${anchored(abs)})`, `${tool}(${anchored(abs)}/**)`];
  return [...protectedList.noAccess.flatMap((abs) => [...both("Read", abs), ...both("Edit", abs)]), ...protectedList.noEdit.flatMap((abs) => both("Edit", abs))];
}

/**
 * The shell sandbox only wraps the agent's shell commands; its Edit and Write tools run in the CLI process outside it. So the files the sandbox
 * stubs out (`SANDBOX_PROTECTED_FILES`, the same list, never a copy) get `Edit` deny rules in the workspace too, as do `.env` and `.env.*` at any depth
 * and the version-control folder's hooks and config. Deny outranks the workspace allow rule; everything else in the workspace stays editable. The workspace's own lock file
 * is regenerated by the runner on the host (`lockfileSync.ts`), not by the agent, so denying it costs no flow.
 */
export function workspaceProtectedEditRules(workspace: string): string[] {
  const root = anchored(workspace);
  return [
    ...SANDBOX_PROTECTED_FILES.map((name) => `Edit(${root}/${name})`),
    `Edit(${root}/.env)`,
    `Edit(${root}/.env.*)`,
    `Edit(${root}/**/.env)`,
    `Edit(${root}/**/.env.*)`,
    // Not the whole `.git` folder: the shell sandbox turns an Edit deny into a read-only bind, and a read-only `.git` leaves no room for the CLI's own
    // placeholders inside it (`.git/config.lock`), which ended every Bash call before it began. The two places that can run code are named instead.
    `Edit(${root}/.git/hooks)`,
    `Edit(${root}/.git/hooks/**)`,
    `Edit(${root}/.git/config)`,
  ];
}

/** One word of an approved check that a `Bash(...)` rule can carry literally: no space, quote, glob, escape or rule delimiter. */
const CHECK_WORD = /^[A-Za-z0-9._/=+@%,:-]{1,200}$/;
const SHELLS: ReadonlySet<string> = new Set(["bash", "sh"]);

/**
 * D#6 RUNNER-AGENT-NO-FULLCHECK: `Bash` deny rules for the repository's approved check, so the agent does not run the whole suite inside its own job (the
 * runner runs it after the agent, in a step of its own with its own limits). Each spelling is denied bare and as a prefix (`Bash(cmd)`, `Bash(cmd:*)`); the
 * CLI matches a rule against each command of a pipeline or `&&` chain, so `cmd 2>&1 | tail` is refused too. Spellings: the signed vector as it is, and for a
 * script started by `bash` or `sh`, the same script under either shell, started directly, with and without a leading `./`.
 *
 * This is the verbatim command and its plain spellings, not a sandbox: an agent that hides the command (a wrapper script, `eval`) is not stopped by it, and
 * the prompt note says plainly not to run it in any form. A vector with a word that cannot be written literally gets no rules (the note still applies); it
 * never refuses the start, since the check is the person's own approved command.
 */
export function checkCommandDenyRules(argv: readonly string[] | undefined): string[] {
  if (argv === undefined || argv.length === 0 || argv.length > 32 || !argv.every((word) => CHECK_WORD.test(word))) return [];
  const commands = [argv.join(" ")];
  const [first, script, ...rest] = argv;
  if (first !== undefined && SHELLS.has(first) && script !== undefined && !script.startsWith("-") && !script.startsWith("/")) {
    const bare = script.startsWith("./") ? script.slice(2) : script;
    for (const form of [bare, `./${bare}`]) {
      for (const lead of ["bash ", "sh ", ""]) {
        // Started directly, a name with no slash is looked up on PATH: that is another command, not this script.
        if (lead === "" && !form.includes("/")) continue;
        commands.push([`${lead}${form}`, ...rest].join(" "));
      }
    }
  }
  return [...new Set(commands)].flatMap((command) => [`Bash(${command})`, `Bash(${command}:*)`]);
}
