/**
 * Re-sign the online roles with fresh expiry even though the targets are about to expire (what the tool refuses once they have): the
 * clock is set to 50 days after signing, when the targets are still valid, with long online lifetimes. Every signature stays genuine.
 */
function refreshTimestampBypassingTargetsCheck(w: World): void {
  const later = new Date(Date.now() - 100 * DAY + 50 * DAY);
  refreshTimestamp({ dir: w.meta, trustedRoot: readFileSync(w.trusted), onlineSigners: [signerFromPem(readFileSync(w.keys.online, "utf8"))], days: { snapshot: 90, timestamp: 90 }, now: later });
}

