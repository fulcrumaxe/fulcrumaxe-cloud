/**
 * The release signing tools (D#6 R6-3) against the runner's REAL TUF client (R6-2a: tuf-js over real TLS to a local server). Nothing
 * here is hand-written metadata: every document the client verifies was produced by `scripts/tuf-release.mjs`, with throwaway keys
 * generated by `scripts/tuf-keygen.mjs` into a temporary directory outside the repository.
 */

const HERE = path.dirname(fileURLToPath(import.meta.url));
const SCRIPTS = path.join(HERE, "..", "..", "scripts");
const DAY = 86_400_000;
const T1 = "v1.0.0/fx-runner-linux-x64";
const T2 = "v1.1.0/fx-runner-linux-x64";
const bytesOf = (version: string): Buffer => Buffer.from(`fx-runner ${version}\n`.repeat(50));

const cleanups: Array<() => Promise<void> | void> = [];
afterEach(async () => {
  for (const fn of cleanups.splice(0)) await fn();
});

interface Keys {
  root: string;
  root2: string;
  targets: string;
  targets2: string;
  online: string;
  online2: string;
  pub: Record<"root" | "root2" | "targets" | "targets2" | "online" | "online2", string>;
}

interface Run {
  code: number;
  out: string;
  err: string;
}

interface World {
  work: string;
  meta: string;
  /** A pristine copy of 1.root.json, made at init-root: the file the owner holds and passes as --trusted-root. */
  trusted: string;
  keys: Keys;
  /** Run the release tool in-process. */
  run(argv: string[], over?: { now?: Date; environment?: NodeJS.ProcessEnv }): Run;
  /** Publish a release of `version` to the metadata directory (artifacts are written, hashed by release-manifest.mjs). */
  publish(version: string, over?: { now?: Date }): void;
  server: TufServer;
  /** Copy the metadata directory to the server. */
  sync(): void;
  client(stateDir?: string): TufClient;
  stateDir: string;
}

async function world(): Promise<World> {
  const work = mkdtempSync(path.join(tmpdir(), "fx-r63-"));
  const keyDir = path.join(work, "keys");
  const names = ["root", "root2", "targets", "targets2", "online", "online2"] as const;
  const keys = { pub: {} } as Keys;
  for (const name of names) {
    const file = path.join(keyDir, `${name}.pem`);
    let out = "";
    expect(keygen(["--out", file], { out: (s: string) => (out += s), err: () => undefined })).toBe(0);
    const pubFile = path.join(work, `${name}.pub.json`);
    writeFileSync(pubFile, out);
    keys[name] = file;
    keys.pub[name] = pubFile;
  }
  const meta = path.join(work, "meta");
  const trusted = path.join(work, "trusted-1.root.json");
  const server = await startTufServer({ rootText: "", metadata: new Map(), files: new Map(), keys: undefined as never });
  const stateDir = mkdtempSync(path.join(tmpdir(), "fx-r63-state-"));
  cleanups.push(async () => {
    await server.close();
    rmSync(work, { recursive: true, force: true });
    rmSync(stateDir, { recursive: true, force: true });
  });
  const world: World = {
    work,
    meta,
    trusted,
    keys,
    server,
    stateDir,
    run(argv, over = {}) {
      let out = "";
      let err = "";
      // The four commands that build on existing metadata need the trusted root; tests that attack it pass their own.
      if (["release", "refresh-timestamp", "rotate-root", "check"].includes(argv[0] ?? "") && !argv.includes("--trusted-root") && existsSync(trusted)) argv = [...argv, "--trusted-root", trusted];
      const code = tool(argv, { now: over.now ?? new Date(), environment: over.environment ?? {}, out: (s: string) => (out += s), err: (s: string) => (err += s) });
      return { code, out, err };
    },
    publish(version, over = {}) {
      const artifacts = path.join(work, `artifacts-${version}`);
      mkdirSync(artifacts, { recursive: true });
      writeFileSync(path.join(artifacts, "fx-runner-linux-x64"), bytesOf(version));
      server.files.set(`v${version}/fx-runner-linux-x64`, bytesOf(version));
      const { file } = writeManifest(artifacts, version);
      const result = world.run(["release", "--dir", meta, "--manifest", file, "--targets-key", keys.targets, "--online-key", keys.online], over);
      expect(result.err).toBe("");
      expect(result.code).toBe(0);
    },
    sync() {
      server.metadata.clear();
      for (const name of readdirSync(meta)) if (name.endsWith(".json")) server.metadata.set(name, readFileSync(path.join(meta, name)));
    },
    client(state = stateDir) {
      const root = readFileSync(path.join(meta, "1.root.json"), "utf8");
      const build: TufBuildConfig = { root, metadataBaseUrl: server.metadataBase, targetBaseUrl: server.targetBase };
      return new TufClient({ stateDir: state, build, ca: server.ca });
    },
  };
  return world;
}

async function initialised(over: { now?: Date } = {}): Promise<World> {
  const w = await world();
  const r = w.run(["init-root", "--dir", w.meta, "--root-key", w.keys.root, "--targets-pubkey", w.keys.pub.targets, "--online-pubkey", w.keys.pub.online], over);
  expect(r.err).toBe("");
  expect(r.code).toBe(0);
  copyFileSync(path.join(w.meta, "1.root.json"), w.trusted);
  return w;
}

const sha = (data: Buffer): string => createHash("sha256").update(data).digest("hex");

function expectVerified(outcome: TufOutcome, version: string): void {
  expect(outcome.ok).toBe(true);
  if (!outcome.ok) return;
  expect(outcome.sha256).toBe(sha(bytesOf(version)));
  expect(readFileSync(outcome.file).equals(bytesOf(version))).toBe(true);
}

const refusedWith = (outcome: TufOutcome, code: string): void => {
  expect(outcome.ok).toBe(false);
  if (outcome.ok) return;
  expect(outcome.state === "paused" ? outcome.code : outcome.state === "refused" ? outcome.code : outcome.state).toBe(code);
};

const cachedRoot = (w: World, state = w.stateDir): number => (JSON.parse(readFileSync(path.join(state, "tuf", "root.json"), "utf8")) as { signed: { version: number } }).signed.version;

/** Damage a file's signatures after signing: keep the first `keep` and drop the rest. The signed part is untouched. */
function keepSignatures(file: string, keep: (keyId: string) => boolean): void {
  const json = JSON.parse(readFileSync(file, "utf8")) as { signatures: Array<{ keyid: string }> };
  json.signatures = json.signatures.filter((s) => keep(s.keyid));
  writeFileSync(file, JSON.stringify(json));
}

describe("acceptance 1: the round trip through the real client", () => {
  it("init-root, release, then refresh-timestamp, then rotate-root, each verified by tuf-js", async () => {
    const w = await initialised();
    w.publish("1.0.0");
    w.sync();
    const client = w.client();
    expectVerified(await client.fetchTarget(T1), "1.0.0");
    const firstTimestamp = JSON.parse(readFileSync(path.join(w.meta, "timestamp.json"), "utf8")).signed.version as number;

    // A weekly re-sign (a second later by the clock the tool is told): a new timestamp (and snapshot) that still verifies.
    const refreshed = w.run(["refresh-timestamp", "--dir", w.meta, "--online-key", w.keys.online], { now: new Date(Date.now() + 1000) });
    expect(refreshed.err).toBe("");
    expect(refreshed.code).toBe(0);
    expect(JSON.parse(readFileSync(path.join(w.meta, "timestamp.json"), "utf8")).signed.version).toBe(firstTimestamp + 1);
    expect(existsSync(path.join(w.meta, "2.snapshot.json"))).toBe(true);
    w.sync();
    expectVerified(await client.fetchTarget(T1), "1.0.0");

    // Root rotation to a new root key: a client that trusts root 1 accepts root 2, and so does one that has never run.
    const rotated = w.run(["rotate-root", "--dir", w.meta, "--root-key", w.keys.root, "--new-root-key", w.keys.root2]);
    expect(rotated.err).toBe("");
    expect(rotated.code).toBe(0);
    expect(rotated.out).not.toContain("run release --renew");
    w.sync();
    expectVerified(await client.fetchTarget(T1), "1.0.0");
    expect(cachedRoot(w)).toBe(2);
    const fresh = mkdtempSync(path.join(tmpdir(), "fx-r63-fresh-"));
    cleanups.push(() => rmSync(fresh, { recursive: true, force: true }));
    expectVerified(await w.client(fresh).fetchTarget(T1), "1.0.0");
    expect(cachedRoot(w, fresh)).toBe(2);
    expect(w.run(["check", "--dir", w.meta]).out).toContain("ok: root 2");
  });

  it("rotating the targets and online keys needs a renew with the new keys, and a client refuses until then", async () => {
    const w = await initialised();
    w.publish("1.0.0");
    const rotated = w.run(["rotate-root", "--dir", w.meta, "--root-key", w.keys.root, "--targets-pubkey", w.keys.pub.targets2, "--online-pubkey", w.keys.pub.online2]);
    expect(rotated.code).toBe(0);
    expect(rotated.out).toContain("run release --renew");
    w.sync();
    refusedWith(await w.client().fetchTarget(T1), "bad_signature");
    // The old keys can no longer sign: the tool refuses them before writing anything.
    const before = readdirSync(w.meta).sort();
    const stale = w.run(["release", "--dir", w.meta, "--renew", "--targets-key", w.keys.targets, "--online-key", w.keys.online]);
    expect(stale.code).toBe(1);
    expect(stale.err).toContain("not one of the targets keys");
    expect(readdirSync(w.meta).sort()).toEqual(before);
    const refused = w.run(["release", "--dir", w.meta, "--renew", "--targets-key", w.keys.targets2, "--online-key", w.keys.online2]);
    expect(refused.code).toBe(1);
    expect(refused.err).toContain("give --artifacts");
    const renewed = w.run(["release", "--dir", w.meta, "--renew", "--targets-key", w.keys.targets2, "--online-key", w.keys.online2, "--artifacts", genuineArtifacts(w, ["1.0.0"])]);
    expect(renewed.err).toBe("");
    expect(renewed.code).toBe(0);
    // The carried list was vouched for by root 1, not the newest root: the tool says so.
    expect(renewed.out).toContain("verified under root 1");
    w.sync();
    expectVerified(await w.client().fetchTarget(T1), "1.0.0");
  });

  it("a new targets version drops a bad release; the older one stays withdrawn and the newer one verifies", async () => {
    const w = await initialised();
    w.publish("1.0.0");
    w.publish("1.1.0");
    w.sync();
    expectVerified(await w.client().fetchTarget(T1), "1.0.0");
    const drop = w.run(["release", "--dir", w.meta, "--drop", "1.0.0", "--targets-key", w.keys.targets, "--online-key", w.keys.online]);
    expect(drop.err).toBe("");
    expect(drop.code).toBe(0);
    expect(drop.out).toContain(T2);
    expect(drop.out).not.toContain(T1);
    w.sync();
    const client = w.client();
    refusedWith(await client.fetchTarget(T1), "target_not_found");
    expectVerified(await client.fetchTarget(T2), "1.1.0");
    // Dropping what is not listed is a mistake, not a no-op.
    expect(w.run(["release", "--dir", w.meta, "--drop", "9.9.9", "--targets-key", w.keys.targets, "--online-key", w.keys.online]).code).toBe(1);
  });

  it("a released file is never replaced by different bytes", async () => {
    const w = await initialised();
    w.publish("1.0.0");
    const artifacts = path.join(w.work, "artifacts-1.0.0");
    writeFileSync(path.join(artifacts, "fx-runner-linux-x64"), "different bytes");
    const { file } = writeManifest(artifacts, "1.0.0");
    const r = w.run(["release", "--dir", w.meta, "--manifest", file, "--targets-key", w.keys.targets, "--online-key", w.keys.online]);
    expect(r.code).toBe(1);
    expect(r.err).toContain("already released with different contents");
  });
});

