export const RUN_EVENTS_SEQ_LOCK_SQL = `SELECT pg_advisory_xact_lock(hashtextextended($1::text, 0))`;
export const runEventsSeqLockKey = (runId: string): string => `run_events_seq:${runId}`;

/** Next `run_events.seq` for `runId`, inside the SAME transaction as the
 * event about to use it -- `MAX(seq)+1`, not a sequence object. H09b1's
 * own event volume is one row per insert plus one per transition (real
 * per-message streaming is H09b2's), and every caller writes one run at
 * a time, so a race here isn't exercised by this PR's test surface. */
async function nextRunEventSeq(client: PoolClient, runId: string): Promise<number> {
  // H14c-3-2c: writers for one run now overlap, so seq is computed under a per-run transaction advisory lock.
  // packages/discussions/src/comments.ts takes the SAME key (it may not import this package); a test pins both.
  await client.query(RUN_EVENTS_SEQ_LOCK_SQL, [runEventsSeqLockKey(runId)]);
  const { rows } = await client.query<{ next: string }>(
    `SELECT COALESCE(MAX(seq), 0) + 1 AS next FROM run_events WHERE run_id = $1`,
    [runId],
  );
  return Number(rows[0]!.next);
}

/**
 * D#2 H11 criterion 2 (redaction at source): every `run_events.payload`
 * that this package writes is redacted HERE, before it is ever written to
 * Postgres. There are two insert sites in this file, `insertRunEvent` below and
 * `insertAgentOutputLine` after it, and each must call `redactEventPayload`
 * itself; tests pin both. (The discussions package has its own writer.)
 */
async function insertRunEvent(
  client: PoolClient,
  accountId: string,
  runId: string,
  kind: string,
  payload: Record<string, unknown>,
): Promise<void> {
  const seq = await nextRunEventSeq(client, runId);
  await client.query(`INSERT INTO run_events (account_id, run_id, seq, kind, payload) VALUES ($1, $2, $3, $4, $5)`, [
    accountId,
    runId,
    seq,
    kind,
    JSON.stringify(redactEventPayload(payload)),
  ]);
}

/**
 * D#2 RLR-1: one `agent.output` row keyed by the record-file line it came from, written on the caller's client so
 * it commits or rolls back with the reader's cursor. A line that already has a row is dropped by the unique key
 * (a replayed or zombie write); the redaction chokepoint above still applies.
 */
export async function insertAgentOutputLine(
  client: PoolClient,
  p: { accountId: string; runId: string; sourceLine: number; payload: Record<string, unknown> },
): Promise<void> {
  const seq = await nextRunEventSeq(client, p.runId);
  await client.query(
    `INSERT INTO run_events (account_id, run_id, seq, kind, payload, source_line) VALUES ($1, $2, $3, 'agent.output', $4, $5)
     ON CONFLICT (run_id, source_line) WHERE kind = 'agent.output' AND source_line IS NOT NULL DO NOTHING`,
    [p.accountId, p.runId, seq, JSON.stringify(redactEventPayload(p.payload)), p.sourceLine],
  );
}

/**
 * D#6 R2b-3: one event a local runner sent, written on the caller's client in the caller's tenant transaction. The runner's
 * own sequence number and the digest of what it sent under that number key the row (migration 0754), so a batch sent twice
 * stores each event once. A second event under a number already stored is dropped; if its body differs from the stored one it
 * is also recorded, as a `runner.event_conflict` row that names the number and nothing else. The payload goes through the same
 * redaction chokepoint as every other row here.
 */
export async function insertRunnerEvent(
  client: PoolClient,
  p: { accountId: string; runId: string; runnerSeq: number; bodySha256: string; payload: Record<string, unknown> },
): Promise<"stored" | "duplicate" | "conflict"> {
  const seq = await nextRunEventSeq(client, p.runId);
  const inserted = await client.query(
    `INSERT INTO run_events (account_id, run_id, seq, kind, payload, runner_seq, runner_body_sha256) VALUES ($1, $2, $3, 'runner.event', $4, $5, $6)
     ON CONFLICT (run_id, runner_seq) WHERE runner_seq IS NOT NULL DO NOTHING`,
    [p.accountId, p.runId, seq, JSON.stringify(redactEventPayload(p.payload)), p.runnerSeq, p.bodySha256],
  );
  if (inserted.rowCount === 1) return "stored";
  const { rows } = await client.query<{ runner_body_sha256: string }>("SELECT runner_body_sha256 FROM run_events WHERE run_id = $1 AND runner_seq = $2", [p.runId, p.runnerSeq]);
  if (rows[0]?.runner_body_sha256 === p.bodySha256) return "duplicate";
  await insertRunEvent(client, p.accountId, p.runId, "runner.event_conflict", { runner_seq: p.runnerSeq });
  return "conflict";
}

