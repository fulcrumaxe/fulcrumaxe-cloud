/**
 * D#2 H09b, correction C10, pass/fail 13: "Every write of
 * `agent_runs.status` is compare-and-set... A single function makes all
 * of these writes." This file is that function, plus the one INSERT that
 * creates a row (test/importBoundary.test.ts checks: every `UPDATE
 * agent_runs` in `packages/runner/src` lives here, with `status = $…` in
 * its `WHERE`).
 *
 * **H09c (correction C37): no direct SQL on `agent_runs` any more.** The
 * INSERT and the compare-and-set UPDATE go through the SECURITY DEFINER
 * functions `agent_run_create` / `agent_run_set_status` (migration 0642),
 * executable only by the NOLOGIN role `agent_run_writer`, inside the same
 * `withTenant` transaction as the `run_events` / domain-event writes (so
 * they stay atomic). `app_user` cannot write the gate-relevant columns any
 * more, so the pool these functions are handed MUST be a login that is a
 * member of BOTH `app_user` and `agent_run_writer`. Public signatures are
 * unchanged (`pool` first) because `packages/pipeline/src` calls them with
 * a single pool: the composition root (H14c) supplies such a pool. This
 * package reads no connection string from `process.env`; the pool is the
 * caller's dependency, with no default. `test/noDirectAgentRunsWrites.test.ts`
 * fails on any `INSERT INTO`/`UPDATE agent_runs` SQL text under
 * `packages/** /src`.
 *
 * Deep-imports `@fx/core`'s `withTenant` (H09b is its first consumer
 * outside `@fx/core` itself; that package has no `main`/`exports` field
 * yet, the same pattern it already uses for `@fx/db`) rather than
 * re-deriving a third copy.
 */

export interface InsertAgentRunParams {
  /** Pre-generated by the caller (`startAgentRun`) -- `admit`'s
   * `reserve()` needs a `runId` that already exists as an `agent_runs`
   * row (the `spend_reservations.run_id` FK), so the id must be known
   * before this INSERT, not read back from it. */
  id: string;
  accountId: string;
  workItemId?: string | null;
  parentRunId?: string | null;
  role: Role;
  /** `'production'` for every H09b sandbox run; `'runner'` for a run a local runner claims (D#6, taken from the target,
   * C12 A1). `'local'` is H04's owner-only dev runner, never written by this package. */
  runtime: "local" | "production" | "runner";
  /** D#6 R3a: the member who started the run. Written by `agent_run_create` only, which refuses a user who is not a
   * member of the account; no later write can change it (0714). */
  initiatedBy?: string | null;
  /**
   * D#6 R4d-5a (C34 section 0): the Spec version the run is built from, written at insert only (`spec_versions.id`; the definer's foreign key refuses
   * another account's). It is what the done check reads the file scope of (`loadAcceptanceScope`), so a Spec re-published mid-run never changes what
   * the run is held to. Absent: the run pins nothing (every run of a role that has no Spec).
   */
  specVersionId?: string | null;
  /**
   * D#6 R4d-5c (C36): the run whose Spec version a follow-on run inherits, when that is not `parentRunId` (a resumed session's own run).
   * When set (even to null, which means "inherit from nobody"), it is the run read; otherwise `parentRunId` is. The create reads that run's `spec_version_id` under the tenant and writes the same value on the
   * new row; it is never the work item's latest version. An explicit `specVersionId` that differs is refused (`SpecVersionMismatchError`).
   * A pushing role (executor, docs-writer) on a `runner_local` repo whose parent has none is refused (`NoSpecVersionError`). Nothing is
   * written in either case.
   */
  specParentRunId?: string | null;
  /** D#5 E9: the environment the run uses, written at insert only. Both or neither (the definer refuses half a record). */
  envVersionId?: string | null;
  imageDigest?: string | null;
  /** Pass/fail 17 / correction C11: written only here, at INSERT time.
   * Nothing in this package ever UPDATEs it. */
  headSha?: string | null;
  /** PR #85 fix round item 4 (CWE-636/362/672): the `repos.execution_mode`
   * `startAgentRun` already resolved before this INSERT (it must succeed
   * against a registered `ExecutionTarget` first -- see
   * `resolveExecutionTarget`), persisted here so `cancelRun` never needs
   * to re-derive it via a `work_items`/`repos` join that can go stale
   * after the fact. `undefined`/`null` for any row not created through
   * `startAgentRun` (this package's other, direct-`insertAgentRun`
   * callers, e.g. its own [pg] test fixtures) -- `cancelRun` treats that
   * absence as "no persisted identity" and fails closed, never guessing
   * `'sandbox'`. */
  executionMode?: string | null;
  /** The `repos.id` `startAgentRun` resolved `executionMode` against.
   * Deliberately NOT re-derived from `work_items.repo_id` at cancel time
   * -- see 0605_execution_mode.sql's header for why that join can go
   * stale (a deleted repo) or simply be a different repo than dispatch
   * actually used. */
  dispatchRepoId?: string | null;
  /** The PR number `startAgentRun`'s caller supplied (meaningful, and
   * required for `sandboxNameFor`, only for the executor role) --
   * likewise persisted once here rather than re-read from a
   * `work_items.gh_number` that can be edited after dispatch. */
  dispatchPrNumber?: number | null;
  /** D#2 H14c-4 (C41 section 4): claims `key` for this run in the SAME
   * transaction as the row (migration 0646), so one key can never own two
   * runs. When the key is already taken the whole transaction rolls back
   * and `IdempotencyKeyTakenError` is thrown: no run row exists. */
  idempotency?: { key: string; requestHash: string };
  /** D#2 H17c-2b (R-ATOMIC): runs INSIDE the create transaction, right after
   * `agent_run_create`, on the same client, so whatever it writes commits with
   * the run row and the idempotency claim or not at all. A throw rolls the whole
   * create back (no run row, no claim). Absent, the create is exactly what it
   * was before this field existed. */
  inCreateTransaction?: (client: PoolClient, runId: string) => Promise<void>;
  /** D#31 API-6b-2 (R-PERSIST): the run's start prompt, kept as one platform-only `run.input` event in the create transaction so a retry can re-use it. */
  startPrompt?: string;
  /** Platform-only facts about how the run was started (a retry's model and escalation), kept in the `run.input` payload under `meta`. */
  startMeta?: Record<string, unknown>;
}

/** D#6 R4d-5c (C36): an explicit Spec version that is not the one the parent run was built against. Nothing was written. */
export class SpecVersionMismatchError extends Error {
  readonly code = "spec_version_mismatch";
  constructor() {
    super("a follow-on run takes its parent's Spec version; another was named");
    this.name = "SpecVersionMismatchError";
  }
}

/** D#6 R4d-5c (C36): a pushing runner run has no Spec version to inherit, so no file list to hold it to. Nothing was written. */
export class NoSpecVersionError extends Error {
  readonly code = "no_spec_version";
  constructor() {
    super("the parent run has no Spec version to inherit");
    this.name = "NoSpecVersionError";
  }
}

/** The roles whose runner runs push commits and so are held to a Spec's file list at done (the same two as `RUNNER_PUSHING_ROLES` in `@fx/gh-policy`, which this package does not depend on). */
const SPEC_PINNED_RUNNER_ROLES: ReadonlySet<string> = new Set(["executor", "docs-writer"]);

/**
 * D#6 R4d-5c (C36): the Spec version a new run is written with. Without a parent it is the caller's (the new-build pin of R4d-5a).
 * With one, it is the parent's, read here on the create's own client so it is under the tenant and inside the create; the caller
 * never computes it. Throws before anything is written.
 */
async function resolveSpecVersionId(client: PoolClient, p: InsertAgentRunParams): Promise<string | null> {
  const parentId = p.specParentRunId !== undefined ? p.specParentRunId : (p.parentRunId ?? null);
  if (!parentId) return p.specVersionId ?? null;
  const { rows } = await client.query<{ spec_version_id: string | null }>("SELECT spec_version_id FROM agent_runs WHERE id = $1 AND account_id = $2", [parentId, p.accountId]);
  const inherited = rows[0]?.spec_version_id ?? null;
  if (p.specVersionId != null && p.specVersionId !== inherited) throw new SpecVersionMismatchError();
  if (inherited === null && isRunnerMode(p.executionMode) && SPEC_PINNED_RUNNER_ROLES.has(p.role)) throw new NoSpecVersionError();
  return inherited;
}

